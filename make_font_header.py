#!/usr/bin/env python3
"""Regenerates Source/MavkaFonts.h: Inter Regular + SemiBold (SIL OFL 1.1), subset to the glyphs MAVKA's UI uses.

    pip install fonttools
    python3 tests/make_font_header.py /path/to/Inter-Regular.otf /path/to/Inter-SemiBold.otf
"""
import os, subprocess, sys, tempfile

UNICODES = ("U+0020-007E,U+00A0-00FF,U+0410,U+0412,U+041A,U+041C,U+2013-2014,U+2018-201E,"
            "U+2022,U+2026,U+2190-2193,U+2212")

def subset(path, out):
    subprocess.check_call(["pyftsubset", path, "--unicodes=" + UNICODES, "--layout-features=kern,tnum,case",
                           "--name-IDs=*", "--name-legacy", "--name-languages=*", "--output-file=" + out])

def main():
    regular, semibold = sys.argv[1], sys.argv[2]
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "..", "Source", "MavkaFonts.h")
    parts = ["// MAVKA interface typeface: Inter (Regular + SemiBold), subset to the glyphs the UI uses.\n"
             "// Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter)\n"
             "// This Font Software is licensed under the SIL Open Font License, Version 1.1\n"
             "// (full text: docs/OFL-Inter.txt, also https://openfontlicense.org). The font may be bundled and\n"
             "// embedded with software, but not sold by itself. Generated by tests/make_font_header.py - do not edit.\n"
             "// Plain static arrays (like JUCE's BinaryData): a constexpr array this big trips MSVC's constexpr step limit.\n"
             "#pragma once\n\nnamespace mavkafonts\n{\n"]
    with tempfile.TemporaryDirectory() as tmp:
        for src, var in ((regular, "interRegular"), (semibold, "interSemiBold")):
            out = os.path.join(tmp, var + ".otf")
            subset(src, out)
            data = open(out, "rb").read()
            parts.append("    static const unsigned int %sSize = %d;\n" % (var, len(data)))
            parts.append("    static const unsigned char %s[] =\n    {\n" % var)
            for i in range(0, len(data), 24):
                parts.append("        " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",\n")
            parts.append("    };\n\n")
    parts.append("} // namespace mavkafonts\n")
    open(target, "w").write("".join(parts))
    print("wrote", target)

if __name__ == "__main__":
    main()
